/** Описание товара для поиска: первая фраза + цена и доставка, не длиннее 160 символов. */
export function productSeoDescription(short: string, price: string): string {
  const tail = ` Цена ${price}. Доставка по Казахстану.`;
  const room = 160 - tail.length;
  const head = short.length > room ? `${short.slice(0, room - 1).replace(/\s+\S*$/, "")}…` : short;
  return head + tail;
}
